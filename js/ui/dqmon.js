// per family: main (b) and second (f) colours as [hue offset or fixed hue, saturation, lightness]; skin for goblins
const PAL = {
  ooze: { b: [0, 70, 55] }, beast: { b: [0, 34, 50] }, insect: { b: [0, 55, 45], f: [52, 88, 58, true] }, plant: { b: [110, 50, 40, true], f: [0, 70, 58] },
  undead: {}, ghost: { b: [0, 30, 84], alpha: 236 }, human: { b: [180, 35, 40], f: [0, 60, 48] }, reptile: { b: [0, 50, 44] }, aquatic: { b: [0, 55, 50], f: [40, 60, 62] },
  bird: { b: [0, 55, 56], f: [20, 50, 44] }, demon: { b: [0, 55, 46], f: [30, 40, 30] }, dragon: { b: [0, 55, 46], f: [20, 50, 38] }, construct: { g: [0, 14, 56] },
  elemental: { f: [0, 92, 55], b: [-10, 95, 74] }, fae: { s: [100, 40, 52, true], f: [0, 50, 44] },
};
function hsl(h, s, l) { h = ((h % 360) + 360) % 360; s /= 100; l /= 100; const k = (n) => (n + h / 30) % 12, f = (n) => l - s * Math.min(l, 1 - l) * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1)); return [Math.round(f(0) * 255), Math.round(f(8) * 255), Math.round(f(4) * 255)]; }
// a cel ramp: shadow, base, light (shadows lean violet, lights lean warm)
const cel = (h, s, l) => [hsl(h + 14, s, l * 0.66), hsl(h, s, l), hsl(h - 8, s * 0.9, Math.min(92, l * 1.25 + 6))];
const FIXED = { o: [32, 22, 34], w: [250, 248, 240], k: [24, 16, 28], r: [196, 44, 58], p: [255, 138, 160], h: [215, 235, 255], N: [74, 46, 30] };
const SHADED = 'bfFynNgsi';

const cache = new Map();
// the sprite for a family and colour: { cv, w, h, eyes }
export function dqSprite(art, hue) {
  const painted = paintSprite(art, hue); if (painted) return painted;      // the newer painted designs (paintmon.js)
  const key = art + ':' + hue; let s = cache.get(key); if (s) return s;
  const map = MAPS[art]; if (!map) return null;
  const P = PAL[art] || {}, pal = {
    b: P.b ? cel(P.b[3] ? P.b[0] : hue + P.b[0], P.b[1], P.b[2]) : cel(hue, 55, 50),
    f: P.f ? cel(P.f[3] ? P.f[0] : hue + P.f[0], P.f[1], P.f[2]) : cel(hue + 30, 50, 48),
    F: cel(40, 45, 80), y: cel(42, 75, 55), n: cel(25, 45, 38), N: cel(22, 40, 22), g: P.g ? cel(hue + P.g[0], P.g[1], P.g[2]) : cel(220, 10, 66),
    s: P.s ? cel(P.s[0], P.s[1], P.s[2]) : cel(28, 55, 72), i: cel(44, 30, 80),
  };
  const glowC = hsl(hue + 180, 95, 66);
  const w = Math.max(...map.map((r) => r.length)) + 2, h = map.length + 2, at = (x, y) => (y >= 1 && y <= map.length ? map[y - 1][x - 1] || '.' : '.');
  const cv = document.createElement('canvas'); cv.width = w; cv.height = h; const c = cv.getContext('2d'), img = c.createImageData(w, h), d = img.data, eyes = [];
  const put = (x, y, [r, g, b], a = 255) => { const i = (y * w + x) * 4; d[i] = r; d[i + 1] = g; d[i + 2] = b; d[i + 3] = a; };
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const ch = at(x, y); if (ch === '.') continue;
    if (ch === 'e') { put(x, y, glowC); eyes.push([x + 0.5, y + 0.5]); continue; }
    if (FIXED[ch]) { put(x, y, FIXED[ch], ch === 'h' ? 150 : 255); continue; }
    const R = pal[ch]; if (!R) continue;
    let tone = 1;
    if (SHADED.includes(ch)) {
      // cel shading: light along the top and left edges of a colour region, shadow along its bottom and right
      const same = (dx, dy) => at(x + dx, y + dy) === ch;
      if (!same(0, 1) || !same(1, 0) || !same(1, 1) || !same(0, 2)) tone = 0;
      if (!same(0, -1) || (!same(-1, 0) && !same(-1, -1))) tone = 2;
    }
    put(x, y, R[tone], art === 'ghost' && ch === 'b' ? P.alpha : 255);
  }
  // a bold outline around the whole sprite
  const src = new Uint8ClampedArray(d);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const i = (y * w + x) * 4; if (src[i + 3]) continue;
    const n = (xx, yy) => xx >= 0 && yy >= 0 && xx < w && yy < h && src[(yy * w + xx) * 4 + 3] > 0;
    if (n(x - 1, y) || n(x + 1, y) || n(x, y - 1) || n(x, y + 1)) { d[i] = 24; d[i + 1] = 16; d[i + 2] = 26; d[i + 3] = 255; } }
  c.putImageData(img, 0, 0);
  const white = document.createElement('canvas'); white.width = w; white.height = h; const wc = white.getContext('2d'); wc.drawImage(cv, 0, 0); wc.globalCompositeOperation = 'source-in'; wc.fillStyle = 'rgba(255,250,240,.9)'; wc.fillRect(0, 0, w, h);
  s = { cv, white, w, h, eyes }; cache.set(key, s); return s;
}
export const hasDq = (art) => !!MAPS[art];
